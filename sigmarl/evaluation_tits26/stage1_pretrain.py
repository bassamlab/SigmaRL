"""Stage 1 of the T-ITS evaluation: pre-training campaign.

Runs main_training.py for every training YAML under --configs (generated by
scripts/generate_configs.py), one process with one thread per run, the most
expensive runs first (highest speed limit, backup-horizon reward). Runs whose
folder already holds final_policy.pth are skipped, so the campaign resumes; an
interrupted run restarts from scratch. Each run's console output goes to
<where_to_save>/stdout.txt, next to training_logs.txt.

Usage (from the repository root):
    python -m sigmarl.evaluation_tits26.stage1_pretrain \\
        --configs configs/tits26/stage1_pretrain [--seeds 1] [--match stage1_bh] \\
        [--workers 10] [--dry_run]
"""

import argparse
import glob
import os
import subprocess
import sys
import threading
import time

import yaml

from sigmarl.constants import SCENARIOS
from sigmarl.evaluation_tits26 import before_stages_filter_benchmark
from sigmarl.evaluation_tits26.before_stages_filter_benchmark import (
    REPO_ROOT,
    base_env,
    run_jobs,
)

SCRIPT = os.path.join(REPO_ROOT, "main_training.py")


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--configs", required=True, help="Folder of training YAML files (recursive)."
    )
    parser.add_argument(
        "--seeds", type=int, nargs="*", default=None, help="Only these seeds."
    )
    parser.add_argument(
        "--match",
        nargs="*",
        default=None,
        help="Only YAML files whose name contains one of these strings.",
    )
    parser.add_argument("--workers", type=int, default=10)
    parser.add_argument(
        "--max_running",
        type=int,
        default=None,
        help="Start a run only while fewer than this many main_training.py "
        "processes run on the machine (also those of other campaigns).",
    )
    parser.add_argument(
        "--dry_run", action="store_true", help="List the runs without starting them."
    )
    return parser.parse_args()


def expected_cost(config: dict) -> float:
    """Relative cost of a run for the ordering: it grows with the number of
    vehicles, and the backup-horizon reward rolls out a braking tail whose
    length grows with the speed limit."""
    cost = float(SCENARIOS[config["scenario_type"]]["max_speed"]) * config["n_agents"]
    if (
        "cbfmargin" in config["rew_method"]
        and config["cbf_margin_reward_condition"] == "backup_horizon"
    ):
        cost *= 3.0
    return cost


# Processes counted by --max_running
GATED_SCRIPTS = (
    "main_training.py",
    "main_testing_cbf_filter.py",
    "stage2_finetune_run.py",
)
_GATE_LOCK = threading.Lock()


def n_running() -> int:
    """Number of running training and rollout processes on the machine."""
    pattern = "|".join(GATED_SCRIPTS)
    result = subprocess.run(["pgrep", "-f", pattern], capture_output=True, text=True)
    return len(result.stdout.split())


def gated_run_job(max_running: int):
    """before_stages_filter_benchmark.run_job that waits for a free slot on the machine."""
    run_job = before_stages_filter_benchmark.run_job

    def run(out_dir: str, command: list, env: dict) -> tuple:
        with _GATE_LOCK:
            while n_running() >= max_running:
                time.sleep(30)
            os.makedirs(out_dir, exist_ok=True)
            log = open(os.path.join(out_dir, "stdout.txt"), "w")
            process = subprocess.Popen(
                command, cwd=REPO_ROOT, env=env, stdout=log, stderr=subprocess.STDOUT
            )
            time.sleep(2)  # Let the process appear before the next check
        code = process.wait()
        log.close()
        return out_dir, code

    return run


def main():
    args = parse_args()
    pattern = os.path.join(os.path.abspath(args.configs), "**", "*.yaml")
    paths = sorted(glob.glob(pattern, recursive=True))
    if not paths:
        sys.exit(f"No YAML files under '{args.configs}'.")
    runs, n_done = [], 0
    for path in paths:
        with open(path) as file:
            config = yaml.safe_load(file)
        if args.seeds is not None and config["seed"] not in args.seeds:
            continue
        name = os.path.basename(path)
        if args.match is not None and not any(text in name for text in args.match):
            continue
        out_dir = os.path.join(REPO_ROOT, config["where_to_save"])
        if os.path.exists(os.path.join(out_dir, "final_policy.pth")):
            n_done += 1
            continue
        runs.append((expected_cost(config), path, out_dir))
    runs.sort(key=lambda run: -run[0])
    print(f"[INFO] {n_done} runs already finished (skipped).")
    jobs = [
        (out_dir, [sys.executable, SCRIPT, "--yaml_config", path], base_env())
        for _, path, out_dir in runs
    ]
    if args.dry_run:
        for _, path, out_dir in runs:
            print(
                f"{os.path.relpath(path, REPO_ROOT)} -> {os.path.relpath(out_dir, REPO_ROOT)}"
            )
        print(f"[INFO] {len(jobs)} runs to do.")
        return
    if args.max_running is not None:
        before_stages_filter_benchmark.run_job = gated_run_job(args.max_running)
    failed = run_jobs(jobs, args.workers)
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
